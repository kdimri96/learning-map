import { useEffect, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import { api, fieldErrors } from '../api.js';
import { Alert, Avatar, Field } from '../components.jsx';

const EMPTY = {
  firstName: '', lastName: '', email: '', phoneNumber: '',
  department: '', designation: '', dateOfJoining: new Date().toISOString().slice(0, 10),
};

/** Used for both "Add employee" (/employees/new) and "Edit" (/employees/:guid/edit). */
export default function EmployeeFormPage() {
  const { guid } = useParams();
  const isEdit = Boolean(guid);
  const navigate = useNavigate();
  const [form, setForm] = useState(EMPTY);
  const [existing, setExisting] = useState(null);
  const [image, setImage] = useState(null);
  const [preview, setPreview] = useState(null);
  const [removeImage, setRemoveImage] = useState(false);
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState(false);
  const errs = fieldErrors(error);

  useEffect(() => {
    if (!isEdit) return;
    api.getEmployee(guid).then((e) => {
      setExisting(e);
      setForm({
        firstName: e.firstName, lastName: e.lastName, email: e.email, phoneNumber: e.phoneNumber ?? '',
        department: e.department, designation: e.designation,
        dateOfJoining: e.dateOfJoining.slice(0, 10),
      });
    }).catch(setError);
  }, [guid, isEdit]);

  useEffect(() => {
    if (!image) { setPreview(null); return undefined; }
    const url = URL.createObjectURL(image);
    setPreview(url);
    return () => URL.revokeObjectURL(url);
  }, [image]);

  const set = (k) => (e) => setForm({ ...form, [k]: e.target.value });

  async function onSubmit(e) {
    e.preventDefault();
    setBusy(true);
    setError(null);

    // multipart/form-data: field names match the C# command properties (binding is case-insensitive).
    const fd = new FormData();
    fd.append('FirstName', form.firstName);
    fd.append('LastName', form.lastName);
    fd.append('Email', form.email);
    if (form.phoneNumber) fd.append('PhoneNumber', form.phoneNumber);
    fd.append('Department', form.department);
    fd.append('Designation', form.designation);
    fd.append('DateOfJoining', form.dateOfJoining);
    if (image) fd.append('Image', image);
    if (isEdit && removeImage && !image) fd.append('RemoveImage', 'true');

    try {
      const saved = isEdit ? await api.updateEmployee(guid, fd) : await api.createEmployee(fd);
      navigate(`/employees/${saved.employeeGuid}`, { replace: true });
    } catch (err) {
      setError(err);
    } finally {
      setBusy(false);
    }
  }

  const departments = ['Engineering', 'HR', 'Finance', 'Sales', 'Operations', 'Marketing'];

  return (
    <div className="stack-lg">
      <Link to={isEdit ? `/employees/${guid}` : '/employees'} className="muted small">← Back</Link>
      <div>
        <h1>{isEdit ? `Edit ${existing?.fullName ?? 'employee'}` : 'Add employee'}</h1>
        <p className="muted">
          {isEdit ? <>PUT /employees/{'{guid}'} · ID <code>{existing?.employeeCode}</code> stays the same.</>
                  : 'POST /employees (multipart/form-data). The employee ID (EMP-xxxxx) is generated by the database.'}
        </p>
      </div>

      <Alert error={error} />

      <form onSubmit={onSubmit} className="card form-grid">
        <Field label="First name *" error={errs.firstname}><input value={form.firstName} onChange={set('firstName')} required maxLength={100} /></Field>
        <Field label="Last name *" error={errs.lastname}><input value={form.lastName} onChange={set('lastName')} required maxLength={100} /></Field>
        <Field label="Email *" error={errs.email}><input type="email" value={form.email} onChange={set('email')} required /></Field>
        <Field label="Phone" error={errs.phonenumber} hint="e.g. +919876543210"><input value={form.phoneNumber} onChange={set('phoneNumber')} /></Field>
        <Field label="Department *" error={errs.department}>
          <input list="departments" value={form.department} onChange={set('department')} required maxLength={100} />
          <datalist id="departments">{departments.map((d) => <option key={d} value={d} />)}</datalist>
        </Field>
        <Field label="Designation *" error={errs.designation}><input value={form.designation} onChange={set('designation')} required maxLength={100} /></Field>
        <Field label="Date of joining *" error={errs.dateofjoining}><input type="date" value={form.dateOfJoining} onChange={set('dateOfJoining')} required /></Field>

        <div className="field full">
          <span className="field-label">Profile image</span>
          <div className="image-picker">
            {preview ? <img className="avatar" src={preview} alt="Preview" style={{ width: 72, height: 72 }} />
              : existing && !removeImage ? <Avatar employee={existing} size={72} />
              : <span className="avatar avatar-initials" style={{ width: 72, height: 72 }}>?</span>}
            <div className="stack">
              <input type="file" accept="image/png,image/jpeg,image/webp" onChange={(e) => setImage(e.target.files?.[0] ?? null)} />
              <span className="field-hint">Optional. JPEG, PNG or WebP, up to 2 MB.</span>
              {isEdit && existing?.hasImage && !image && (
                <label className="checkbox">
                  <input type="checkbox" checked={removeImage} onChange={(e) => setRemoveImage(e.target.checked)} />
                  Remove current image
                </label>
              )}
              {errs.image && <span className="field-error">{errs.image}</span>}
            </div>
          </div>
        </div>

        <div className="full actions">
          <button className="btn btn-primary" disabled={busy}>{busy ? 'Saving…' : isEdit ? 'Save changes' : 'Create employee'}</button>
          <Link className="btn btn-ghost" to={isEdit ? `/employees/${guid}` : '/employees'}>Cancel</Link>
        </div>
      </form>
    </div>
  );
}
