using AutoMapper;
using LearningMap.Application.Commands.Employees;
using LearningMap.Application.Dtos;
using LearningMap.Application.Interfaces.Services;
using LearningMap.Domain.Entities;

namespace LearningMap.Application.Mappings;

/// <summary>AutoMapper copies properties with the same name automatically; we only spell out the exceptions.</summary>
public class MappingProfile : Profile
{
    public MappingProfile()
    {
        // Entity -> DTO (for responses)
        CreateMap<Employee, EmployeeDto>()
            .ForMember(d => d.FullName, o => o.MapFrom(s => s.FirstName + " " + s.LastName))
            .ForMember(d => d.HasImage, o => o.MapFrom(s => s.ProfileImageBlobName != null))
            .ForMember(d => d.ImageUrl, o => o.Ignore()); // needs IImageStore, set in ToDto() below

        CreateMap<AppUser, UserSummaryDto>();

        // Command -> Entity (for create/update). Values the client must NOT control are ignored.
        CreateMap<EmployeeCommandBase, Employee>()
            .ForMember(d => d.FirstName, o => o.MapFrom(s => s.FirstName.Trim()))
            .ForMember(d => d.LastName, o => o.MapFrom(s => s.LastName.Trim()))
            .ForMember(d => d.Email, o => o.MapFrom(s => s.Email.Trim().ToLowerInvariant()))
            .ForMember(d => d.PhoneNumber, o => o.MapFrom(s => string.IsNullOrWhiteSpace(s.PhoneNumber) ? null : s.PhoneNumber.Trim()))
            .ForMember(d => d.Department, o => o.MapFrom(s => s.Department.Trim()))
            .ForMember(d => d.Designation, o => o.MapFrom(s => s.Designation.Trim()))
            .ForMember(d => d.DateOfJoining, o => o.MapFrom(s => s.DateOfJoining.Date))
            .ForMember(d => d.EmployeeId, o => o.Ignore())
            .ForMember(d => d.EmployeeGuid, o => o.Ignore())
            .ForMember(d => d.EmployeeCode, o => o.Ignore())        // generated by the database
            .ForMember(d => d.ProfileImageBlobName, o => o.Ignore())
            .ForMember(d => d.ImageUploadedDate, o => o.Ignore())
            .ForMember(d => d.IsDeleted, o => o.Ignore())
            .ForMember(d => d.CreatedBy, o => o.Ignore())
            .ForMember(d => d.CreatedDate, o => o.Ignore())
            .ForMember(d => d.ModifiedBy, o => o.Ignore())
            .ForMember(d => d.ModifiedDate, o => o.Ignore());
    }
}

public static class EmployeeMappingExtensions
{
    public static EmployeeDto ToDto(this IMapper mapper, Employee employee, IImageStore imageStore)
    {
        var dto = mapper.Map<EmployeeDto>(employee);
        dto.ImageUrl = employee.ProfileImageBlobName is null ? null : imageStore.GetReadUrl(employee.ProfileImageBlobName);
        return dto;
    }
}
